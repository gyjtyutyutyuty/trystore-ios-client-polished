#!/usr/bin/env node
import { createCipheriv, randomBytes } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const sourceDir = resolve(process.argv[2] ?? 'ThreeOneOSFive/Patches');
const outputFile = resolve(process.argv[3] ?? 'ThreeOneOSFive/helpers/GeneratedPatchBundle.swift');
const key = Buffer.from(process.env.PATCH_BUNDLE_KEY_BASE64 ?? '', 'base64');
if (key.length !== 32) {
  throw new Error('Set PATCH_BUNDLE_KEY_BASE64 to a base64-encoded 32-byte AES key.');
}

const files = (await readdir(sourceDir, { withFileTypes: true }))
  .filter(entry => entry.isFile() && entry.name.endsWith('.3105'))
  .sort((a, b) => a.name.localeCompare(b.name));
if (files.length === 0) throw new Error(`No .3105 resources found in ${sourceDir}`);

const entries = [];
for (const entry of files) {
  const name = Buffer.from(entry.name, 'utf8');
  const data = await readFile(join(sourceDir, entry.name));
  if (name.length > 0xffff || data.length > 0xffffffff) {
    throw new Error(`Resource is too large for the archive format: ${entry.name}`);
  }
  const nameLength = Buffer.alloc(2);
  nameLength.writeUInt16BE(name.length);
  const dataLength = Buffer.alloc(4);
  dataLength.writeUInt32BE(data.length);
  entries.push(nameLength, dataLength, name, data);
}

// Names are part of the encrypted archive, not exposed in the generated source.
const archive = Buffer.concat([
  Buffer.from('TBP1', 'ascii'),
  Buffer.from([files.length >> 8, files.length & 0xff]),
  ...entries,
]);
const nonce = randomBytes(12);
const cipher = createCipheriv('aes-256-gcm', key, nonce);
const ciphertext = Buffer.concat([cipher.update(archive), cipher.final()]);
const combined = Buffer.concat([nonce, ciphertext, cipher.getAuthTag()]);
const base64 = combined.toString('base64');
const chunks = base64.match(/.{1,80000}/g) ?? [];
const source = `// Generated by scripts/encrypt_bundled_patches.mjs. Do not edit by hand.\nenum GeneratedPatchBundle {\n    static let base64Chunks: [String] = [\n${chunks.map(chunk => `        "${chunk}"`).join(',\n')}\n    ]\n}\n`;
await writeFile(outputFile, source, { mode: 0o644 });
console.log(`Encrypted ${files.length} resources into one source-embedded payload (${combined.length} bytes).`);
console.log(`Generated ${outputFile}; resource names are encrypted inside the payload.`);
